|---------|-------|-----|
|         |       |     |

## CI/CD

- Platform:
- Config:

## Notes

EOF
    echo "  [+] Created pipeline.md"
fi

# Download system.md template (how the system works) - first install only
SYSTEM_PATH="$DEST_DIR/system.md"
if [ ! -f "$SYSTEM_PATH" ]; then
    if (command -v curl &> /dev/null && curl -fsSL "$REPO_URL/system.md" -o "$SYSTEM_PATH" 2>/dev/null) || \
       (command -v wget &> /dev/null && wget -q "$REPO_URL/system.md" -O "$SYSTEM_PATH" 2>/dev/null); then
        echo "  [+] Created system.md (architecture, protocols, hardware, config)"
    else
        rm -f "$SYSTEM_PATH"
        echo "  [!] Could not download system.md (non-fatal)."
    fi
else
    echo "  [=] system.md already exists (preserved)"
fi

# Create or download fail_log.md (Failure & Anti-Pattern Memory)
FAIL_LOG_PATH="$DEST_DIR/fail_log.md"
if [ ! -f "$FAIL_LOG_PATH" ]; then
    if command -v curl &> /dev/null && curl -fsSL "$REPO_URL/fail_log.md" -o "$FAIL_LOG_PATH" 2>/dev/null; then
        echo "  [+] Installed fail_log.md (Failure Memory)"
    elif command -v wget &> /dev/null && wget -q "$REPO_URL/fail_log.md" -O "$FAIL_LOG_PATH" 2>/dev/null; then
        echo "  [+] Installed fail_log.md (Failure Memory)"
    else
        cat > "$FAIL_LOG_PATH" << 'EOF'
# ⚠️ Agent Fail Log & Anti-Patterns

> **Read this file BEFORE planning or coding to avoid repeating past mistakes.**
> Whenever an approach fails (❌), hits a dead-end, or takes more than 2 attempts to fix, record the root cause and the "Do Not Repeat" rule here.

---
EOF
        echo "  [+] Created fail_log.md (Failure Memory)"
    fi
else
    echo "  [=] fail_log.md already exists (preserved)"
fi

# Create active.md template (read first by every new session)
ACTIVE_PATH="$DEST_DIR/active.md"
if [ ! -f "$ACTIVE_PATH" ]; then
    cat > "$ACTIVE_PATH" << 'EOF'
# Active Context
**Updated:** YYYY-MM-DD | **Agent:** (agent name + model)

## Current Status
Not started yet.

## Deliverables
| Deliverable | Status | Notes |
|-------------|--------|-------|
|             |        |       |

## Handoff
- **Did:**
- **Found:**
- **Next:**
EOF
    echo "  [+] Created active.md"
fi

# Download Cline skill template (SKILL.md)
if [ "$GLOBAL" = true ]; then
    CLINE_SKILL_DIR="$HOME/.cline/skills/agent-journal"
    echo "  [*] Downloading Cline skill (global)..."
else
    CLINE_SKILL_DIR="$(pwd)/.cline/skills/agent-journal"
    echo "  [*] Downloading Cline skill..."
fi
mkdir -p "$CLINE_SKILL_DIR"
if command -v curl &> /dev/null; then
    curl -fsSL "$REPO_URL/cline-skill.md" -o "$CLINE_SKILL_DIR/SKILL.md" && echo "  [+] Successfully installed SKILL.md (Cline skill)" || echo "  [!] Could not download Cline skill (non-fatal)."
elif command -v wget &> /dev/null; then
    wget -q "$REPO_URL/cline-skill.md" -O "$CLINE_SKILL_DIR/SKILL.md" && echo "  [+] Successfully installed SKILL.md (Cline skill)" || echo "  [!] Could not download Cline skill (non-fatal)."
else
    echo "  [!] Could not download Cline skill (non-fatal)."
fi

# Install Hermes Agent skill (~/.hermes/skills/agent-journal/SKILL.md & .skills/agent-journal/SKILL.md) + SOUL.md
if [ "$GLOBAL" = true ] || [ -d "$HOME/.hermes" ]; then
    mkdir -p "$HOME/.hermes/skills/agent-journal"
    cp "$AGENTS_MD_PATH" "$HOME/.hermes/skills/agent-journal/SKILL.md" 2>/dev/null && echo "  [+] Installed Hermes global skill (~/.hermes/skills/agent-journal/SKILL.md)" || true
    rm -f "$HOME/.hermes/.skills_prompt_snapshot.json" 2>/dev/null || true

    HERMES_SOUL="$HOME/.hermes/SOUL.md"
    if [ ! -f "$HERMES_SOUL" ] || ! grep -q "agent-journal" "$HERMES_SOUL" 2>/dev/null; then
        cat >> "$HERMES_SOUL" << 'EOF'

## Agent Journal & Fail Log Protocol
- Always follow the protocols defined in `.skills/agent-journal/SKILL.md` (or load via `skill_view("agent-journal")` / `~/.hermes/skills/agent-journal/SKILL.md`) before and after modifying files.
- Read `.agents/PROJECT_MAP.md`, `.agents/system.md`, `.agents/pipeline.md`, and `.agents/fail_log.md` (if they exist) before planning or writing code.
- Keep `.agents/system.md` (how the system works) and `.agents/pipeline.md` (how to operate it) up to date in the same task as the change. Never write secret values under `.agents/`.
- Always log plans and step-by-step execution in `.agents/Agent-Journal.md`, and record any failed approaches (`❌`) in `.agents/fail_log.md`.
EOF
        echo "  [+] Bound agent-journal into Hermes System Prompt (~/.hermes/SOUL.md)"
    fi
fi
if [ "$GLOBAL" = false ]; then
    mkdir -p "$(pwd)/.skills/agent-journal"
    cp "$AGENTS_MD_PATH" "$(pwd)/.skills/agent-journal/SKILL.md" 2>/dev/null && echo "  [+] Installed local skill (.skills/agent-journal/SKILL.md)" || true
fi

# Download and run Agent Map (only for local installs)
if [ "$GLOBAL" = false ]; then
    echo "  [*] Downloading Agent Map generator..."
    MAP_SCRIPT_PATH="$(pwd)/agent-map.py"
    if command -v curl &> /dev/null; then
        curl -fsSL "$REPO_URL/agent-map.py" -o "$MAP_SCRIPT_PATH"
    else
        wget -q "$REPO_URL/agent-map.py" -O "$MAP_SCRIPT_PATH"
    fi
    echo "  [+] Successfully downloaded agent-map.py"
    echo "  [*] Generating Project Map..."
    if command -v python3 &> /dev/null; then
        python3 "$MAP_SCRIPT_PATH"
    elif command -v python &> /dev/null; then
        python "$MAP_SCRIPT_PATH"
    else
        echo "  [!] Could not run Python automatically."
    fi
fi

# Keep .agents/ shareable through git - ignore only the private and backup folders
# (a project that already ignores .agents/ is left as it is)
if [ "$GLOBAL" = false ] && [ -f ".gitignore" ]; then
    if ! grep -q "\.agents/" .gitignore; then
        printf "\n# Agent Journal (local-only parts; the rest of .agents/ is meant to be committed)\n.agents/private/\n.agents/backup/\n" >> .gitignore
        echo "  [+] Added .agents/private/ and .agents/backup/ to .gitignore"
    fi
fi

# Configure AI Auto-Journaling (all platforms)
RULE_TEXT="\n# Agent Journal Rules\n- Read and follow .agents/AGENTS.md for journaling and context rules.\n- START: Read .agents/active.md before doing anything else in a new chat.\n- AFTER EVERY TASK: Update .agents/active.md (status, deliverables table, Did/Found/Next handoff) and sign journal entries with your agent name.\n- CONTEXT & FAIL LOG: Read .agents/PROJECT_MAP.md, .agents/system.md, .agents/pipeline.md, and .agents/fail_log.md (if they exist) BEFORE planning or writing code so you never repeat past failures.\n- SYSTEM DOCS: When a change alters architecture, a protocol/API, hardware, critical config, or how to set up/run/use the project, update .agents/system.md or .agents/pipeline.md in the same task. Never write secret values under .agents/.\n- PRE-JOURNALING: ALWAYS write an initial entry in .agents/Agent-Journal.md BEFORE making any code changes. Set status to In Progress and list planned actions.\n- EXECUTION LOG: Before each action, log it with status icon (planned/in progress/done/failed). Write the step BEFORE executing it.\n- FAILURE LOGGING: Whenever a step fails (❌) or hits a dead-end, record the root cause and 'Do Not Repeat' rule in .agents/fail_log.md.\n- COMPLETION: Once work is complete, update the entry status to Complete and generate .agents/Agent-Journal.html from the markdown.\n- Do not ask for permission to journal, just do it automatically.\n"

if [ "$GLOBAL" = false ]; then
    echo "  [*] Configuring AI Auto-Journaling for all platforms..."

    # Cline - .clinerules/agent-journal.md (always-active workspace rule)
    if ! ([ -f ".clinerules/agent-journal.md" ] && grep -q "Agent Journal" ".clinerules/agent-journal.md"); then
        mkdir -p ".clinerules"
        printf "%b" "$RULE_TEXT" >> ".clinerules/agent-journal.md"
        echo "  [+] Configured .clinerules/agent-journal.md (Cline rule)"
    fi

    # Cursor
    if ! ([ -f ".cursorrules" ] && grep -q "Agent Journal" ".cursorrules"); then
        printf "%b" "$RULE_TEXT" >> ".cursorrules"
        echo "  [+] Configured .cursorrules"
    fi

    # Windsurf
    if ! ([ -f ".windsurfrules" ] && grep -q "Agent Journal" ".windsurfrules"); then
        printf "%b" "$RULE_TEXT" >> ".windsurfrules"
        echo "  [+] Configured .windsurfrules"
    fi

    # Root AGENTS.md - thin pointer read by Codex, Cline, Cursor, Copilot, etc. (append, never overwrite)
    ROOT_AGENTS_TEXT='# Agent Journal\n\nBefore any task, read `.agents/active.md`, then follow the rules in `.agents/AGENTS.md`.\n\n@.agents/AGENTS.md\n'
    if [ ! -f "AGENTS.md" ]; then
        printf "%b" "$ROOT_AGENTS_TEXT" > "AGENTS.md"
        echo "  [+] Created AGENTS.md"
    elif ! grep -q "\.agents/AGENTS\.md" "AGENTS.md"; then
        printf "\n%b" "$ROOT_AGENTS_TEXT" >> "AGENTS.md"
        echo "  [+] Updated AGENTS.md with journal pointer"
    fi

    # Claude Code - CLAUDE.md imports root AGENTS.md so every agent shares one rule set
    if [ ! -f "CLAUDE.md" ]; then
        printf "@AGENTS.md\n" > "CLAUDE.md"
        echo "  [+] Created CLAUDE.md"
    elif ! grep -q "AGENTS\.md" "CLAUDE.md"; then
        printf "\n@AGENTS.md\n" >> "CLAUDE.md"
        echo "  [+] Updated CLAUDE.md with AGENTS.md import"
    fi

    # GitHub Copilot - .github/copilot-instructions.md
    mkdir -p ".github"
    if ! ([ -f ".github/copilot-instructions.md" ] && grep -q "Agent Journal" ".github/copilot-instructions.md"); then
        printf "%b" "$RULE_TEXT" >> ".github/copilot-instructions.md"
        echo "  [+] Configured .github/copilot-instructions.md"
    fi

    # Antigravity
    mkdir -p ".antigravity"
    if [ ! -f ".antigravity/extensions.json" ]; then
        cat > ".antigravity/extensions.json" << 'EOF'
{"version":"1.0","extensions":[{"id":"unified-agent-skill","name":"Agent Context + Journal","description":"Universal journaling, context saving, and project mapping","enabled":true,"path":"../.agents/AGENTS.md"}]}
EOF
        echo "  [+] Configured .antigravity/extensions.json"
    fi
else
    # Cline global rule (~/.cline/rules/agent-journal.md)
    mkdir -p "$HOME/.cline/rules"
    if ! ([ -f "$HOME/.cline/rules/agent-journal.md" ] && grep -q "Agent Journal" "$HOME/.cline/rules/agent-journal.md"); then
        printf "%b" "$RULE_TEXT" >> "$HOME/.cline/rules/agent-journal.md"
        echo "  [+] Configured Cline global rule (~/.cline/rules/agent-journal.md)"
    fi
fi

echo ""
echo "  ✅ Ready to start journaling!"
echo ""
echo "  ✨ Auto-Journaling configured for:"
echo "    - Claude Code    (CLAUDE.md -> @AGENTS.md)"
echo "    - Codex & others (AGENTS.md)"
echo "    - Cursor         (.cursorrules)"
echo "    - Windsurf       (.windsurfrules)"
echo "    - GitHub Copilot (.github/copilot-instructions.md)"
echo "    - Antigravity    (.antigravity/extensions.json)"
echo "    - Hermes Agent   (~/.hermes/skills/agent-journal/ + .skills/agent-journal/)"
if [ "$GLOBAL" = true ]; then
    echo "    - Cline          (global: ~/.cline/rules/ + ~/.cline/skills/)"
else
    echo "    - Cline          (.clinerules/ + .cline/skills/)"
fi
echo "  ⚠️ Failure Memory enabled (.agents/fail_log.md)."
echo "  📐 System Docs: fill in .agents/system.md and .agents/pipeline.md (or ask your AI to)."
echo "  🌐 HTML Companion enabled. Agent will generate Agent-Journal.html after each session."
echo ""
echo "  📊 Open .agents/Agent-Journal.html in any browser to view your journal dashboard"
echo ""
echo "  ──────────────────────────────────────"
echo "  Options:  install.sh --global  (install to ~/.agents/)"
echo "            install.sh --force   (overwrite without asking)"
echo ""
