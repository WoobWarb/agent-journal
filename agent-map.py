import os
import re
import json
from pathlib import Path

IGNORE_DIRS = {
    '.git', 'node_modules', '.venv', 'venv', '__pycache__',
    '.agents', 'dist', 'build', '.idea', '.vscode', '.next',
    '.nuxt', '.output', 'coverage', '.pytest_cache', '.mypy_cache',
    '.svn', '.hg', '.tox', '__snapshots__',
}

IGNORE_EXTS = {
    '.pyc', '.pyo', '.pyd', '.so', '.dll', '.exe',
    '.png', '.jpg', '.jpeg', '.gif', '.mp4', '.mp3', '.wav',
    '.zip', '.tar', '.gz', '.lock', '.ico', '.svg', '.woff', '.woff2'
}

# Top-level definitions worth listing per file, so the map shows what a file contains, not just its name
_C_FUNC = r'^(?!(?:if|for|while|switch|return|else|do)\b)[A-Za-z_][\w\s\*&:<>,]*?\b(\w+)\s*\([^;{]*\)\s*(?:const\s*)?\{?\s*$'
_JS = [r'^(?:export\s+)?(?:default\s+)?(?:async\s+)?function\*?\s+(\w+)',
       r'^(?:export\s+)?(?:default\s+)?(?:abstract\s+)?class\s+(\w+)',
       r'^(?:export\s+)?(?:const|let)\s+(\w+)\s*=\s*(?:async\s*)?(?:\(|function\b)',
       r'^export\s+(?:interface|type|enum)\s+(\w+)']
SYMBOL_PATTERNS = {
    '.py': [r'^(?:async\s+)?def\s+(\w+)', r'^class\s+(\w+)'],
    '.js': _JS, '.jsx': _JS, '.ts': _JS, '.tsx': _JS, '.mjs': _JS, '.cjs': _JS,
    '.c': [_C_FUNC], '.h': [_C_FUNC], '.cpp': [_C_FUNC, r'^(?:class|struct)\s+(\w+)'],
    '.hpp': [_C_FUNC, r'^(?:class|struct)\s+(\w+)'], '.ino': [_C_FUNC],
    '.go': [r'^func\s+(?:\([^)]*\)\s*)?(\w+)', r'^type\s+(\w+)'],
    '.rs': [r'^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)',
            r'^(?:pub(?:\([^)]*\))?\s+)?(?:struct|enum|trait)\s+(\w+)'],
    '.ps1': [r'^function\s+([\w-]+)'],
    '.sh': [r'^(?:function\s+)?(\w+)\s*\(\)\s*\{?'],
    '.md': [r'^#{1,2}\s+(.+?)\s*$'],
}
MAX_SYMBOLS = 20
MAX_SCAN_BYTES = 300_000

def extract_symbols(file_path):
    patterns = SYMBOL_PATTERNS.get(file_path.suffix.lower())
    if not patterns or file_path.stat().st_size > MAX_SCAN_BYTES:
        return []
    compiled = [re.compile(p) for p in patterns]
    symbols = []
    in_fence = False
    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            if file_path.suffix.lower() == '.md' and line.startswith('```'):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            for pattern in compiled:
                m = pattern.match(line.rstrip())
                if m and m.group(1) not in symbols:
                    symbols.append(m.group(1))
                    break
    return symbols

def generate_map(root_dir='.'):
    root_path = Path(root_dir)
    tree_lines = []
    file_details = []

    for current_root, dirs, files in os.walk(root_path):
        dirs[:] = [d for d in dirs if d not in IGNORE_DIRS]

        rel_path = Path(current_root).relative_to(root_path)
        level = len(rel_path.parts) if rel_path.name else 0
        indent = '  ' * level

        if rel_path.name:
            tree_lines.append(f"{indent}📂 {rel_path.name}/")

        sub_indent = '  ' * (level + 1)
        for f in sorted(files):
            file_path = Path(current_root) / f

            if f.startswith('.'):
                continue

            tree_lines.append(f"{sub_indent}📄 {f}")

            if file_path.suffix.lower() in IGNORE_EXTS:
                continue

            context = ""
            try:
                with open(file_path, 'r', encoding='utf-8') as file_obj:
                    lines = []
                    for _ in range(5):
                        try:
                            line = next(file_obj).strip()
                            if line and not line.startswith(('import', 'from', '//', '/*', '*', '#!')):
                                lines.append(line)
                        except StopIteration:
                            break
                    context = " ".join(lines)
                symbols = extract_symbols(file_path)
            except Exception:
                context = "[Binary or unreadable]"
                symbols = []

            file_details.append({
                "path": str(file_path.relative_to(root_path)).replace('\\', '/'),
                "ext": file_path.suffix,
                "context": context[:150] + "..." if len(context) > 150 else context,
                "symbols": symbols
            })

    return tree_lines, file_details

def write_project_map(tree_lines, file_details):
    agents_dir = Path('.agents')
    agents_dir.mkdir(exist_ok=True)

    map_path = agents_dir / 'PROJECT_MAP.md'
    json_path = agents_dir / 'graph.json'

    with open(map_path, 'w', encoding='utf-8') as f:
        f.write("# Project Map\n\n")
        f.write("> Auto-generated by agent-map.py. Shows what files exist and what they define.\n")
        f.write("> For how the system works, read `system.md`; for how to run it, read `pipeline.md`.\n\n")
        f.write("## File Tree\n```\n")
        f.write("\n".join(tree_lines))
        f.write("\n```\n\n")
        f.write("## File Contexts\n\n")
        for detail in file_details:
            f.write(f"- **`{detail['path']}`**")
            if detail['context']:
                f.write(f" — {detail['context']}")
            f.write("\n")
            if detail['symbols']:
                shown = detail['symbols'][:MAX_SYMBOLS]
                more = len(detail['symbols']) - len(shown)
                f.write("  - defines: " + ", ".join(f"`{name}`" for name in shown))
                f.write(f" (+{more} more)\n" if more else "\n")

    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(file_details, f, indent=2)

    print(f"Generated: {map_path}")
    print(f"Generated: {json_path}")
    print(f"Total files mapped: {len(file_details)}")

if __name__ == '__main__':
    print("Generating Agent Project Map...")
    tree, details = generate_map()
    write_project_map(tree, details)
